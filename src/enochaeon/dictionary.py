"""A dictionary made from calls/lexicon.json: Enochian to English, and English to Enochian.

The lexicon is the one place a word and its English are kept. Nothing is added
here and no meaning is worked out. The dictionary is written beside the lexicon
as dictionary.md and dictionary.html, and is made again whenever the lexicon
changes. A word the lexicon gives no English is listed apart from the rest.

How a word is said is not shown.
"""

from __future__ import annotations

import html
from dataclasses import dataclass
from pathlib import Path

from enochaeon.errors import EnochaeonError
from enochaeon.page import LETTERS_CREDIT, fold, font_base64
from enochaeon.roots import _calls_dir, _entries

LEXICON_NAME = "lexicon.json"
MARKDOWN_NAME = "dictionary.md"
HTML_NAME = "dictionary.html"
TITLE = "Enochian dictionary"
# What stands between two English glosses of one word. A gloss may have a comma in it.
BETWEEN = "; "
_MARKDOWN_MARKS = "\\`*_[]<>|"


@dataclass(frozen=True)
class Entry:
    """One word of the lexicon as it is written there."""

    word: str
    others: tuple[str, ...]
    part: str
    glosses: tuple[str, ...]


def load_dictionary(folder: Path | None = None) -> tuple[Entry, ...]:
    """Every word of the lexicon in the directory, in the order of the alphabet."""
    path = (folder or _calls_dir()) / LEXICON_NAME
    found: list[Entry] = []
    for index, raw in enumerate(_entries(path), 1):
        names = _unique(path, index, "spelling", [raw.get("root"), *(raw.get("variants") or [])])
        if not names:
            raise EnochaeonError(f"{path.name} entry {index} needs a spelling.")
        glosses = raw.get("english_glosses")
        if not isinstance(glosses, list):
            raise EnochaeonError(f"{path.name} entry {index} needs english_glosses.")
        found.append(
            Entry(
                word=names[0],
                others=tuple(names[1:]),
                part=" ".join(str(raw.get("pos") or "").split()),
                glosses=tuple(_unique(path, index, "gloss", glosses)),
            )
        )
    return tuple(sorted(found, key=lambda entry: entry.word.casefold()))


def by_english(entries: tuple[Entry, ...]) -> tuple[tuple[str, tuple[str, ...]], ...]:
    """Each English gloss with the words that have it. Capitals do not make two glosses."""
    written: dict[str, str] = {}
    words: dict[str, list[str]] = {}
    for entry in entries:
        for gloss in entry.glosses:
            key = gloss.casefold()
            written.setdefault(key, gloss)
            words.setdefault(key, []).append(entry.word)
    return tuple((written[key], tuple(words[key])) for key in sorted(written))


def render_markdown(entries: tuple[Entry, ...]) -> str:
    """The dictionary as a Markdown file."""
    known = [entry for entry in entries if entry.glosses]
    unknown = [entry for entry in entries if not entry.glosses]
    lines = [
        f"# {TITLE}",
        "",
        f"Made by `enochaeon dictionary` from [`{LEXICON_NAME}`]({LEXICON_NAME}). "
        "Do not edit this file. Change the lexicon and make it again.",
        "",
        _summary(entries),
        "",
        "## Enochian to English",
        "",
        "| Word | Other spellings | Part of speech | English |",
        "| --- | --- | --- | --- |",
    ]
    for entry in known:
        lines.append(
            f"| {_md(entry.word)} | {_md(', '.join(entry.others))} | {_md(entry.part)} "
            f"| {_md(BETWEEN.join(entry.glosses))} |"
        )
    lines += ["", "## English to Enochian", "", "| English | Words |", "| --- | --- |"]
    for gloss, words in by_english(entries):
        lines.append(f"| {_md(gloss)} | {_md(', '.join(words))} |")
    lines += ["", "## Words with no English", "", "| Word | Other spellings |", "| --- | --- |"]
    for entry in unknown:
        lines.append(f"| {_md(entry.word)} | {_md(', '.join(entry.others))} |")
    return "\n".join(lines) + "\n"


def render_html(entries: tuple[Entry, ...]) -> str:
    """The dictionary as one HTML page, with each word in Enochian letters."""
    known = [entry for entry in entries if entry.glosses]
    unknown = [entry for entry in entries if not entry.glosses]
    to_english = "".join(
        f"<tr>{_letters(entry.word)}<td class=\"word\">{_h(entry.word)}</td><td>{_h(', '.join(entry.others))}</td>"
        f"<td>{_h(entry.part)}</td><td>{_h(BETWEEN.join(entry.glosses))}</td></tr>\n"
        for entry in known
    )
    to_enochian = "".join(
        f"<tr><td>{_h(gloss)}</td><td class=\"word\">{_h(', '.join(words))}</td></tr>\n"
        for gloss, words in by_english(entries)
    )
    no_english = "".join(
        f"<tr>{_letters(entry.word)}<td class=\"word\">{_h(entry.word)}</td><td>{_h(', '.join(entry.others))}</td></tr>\n"
        for entry in unknown
    )
    return _PAGE.format(
        font=font_base64(),
        title=_h(TITLE),
        lexicon=_h(LEXICON_NAME),
        summary=_h(_summary(entries)),
        to_english=to_english,
        to_enochian=to_enochian,
        no_english=no_english,
        credit=LETTERS_CREDIT,
    )


def write_dictionary(folder: Path | None = None, force: bool = False) -> tuple[Path, Path]:
    """Write dictionary.md and dictionary.html beside the lexicon."""
    folder = folder or _calls_dir()
    if not folder.is_dir():
        raise EnochaeonError(f"No such directory: {folder}")
    markdown = folder / MARKDOWN_NAME
    page = folder / HTML_NAME
    for dest in (markdown, page):
        if dest.exists() and not force:
            raise EnochaeonError(f"{dest} already exists. Pass --force to replace it.")
    entries = load_dictionary(folder)
    markdown.write_text(render_markdown(entries), encoding="utf-8")
    page.write_text(render_html(entries), encoding="utf-8")
    return markdown, page


def _summary(entries: tuple[Entry, ...]) -> str:
    known = sum(1 for entry in entries if entry.glosses)
    return (
        f"{len(entries)} words: {known} with English and {len(entries) - known} with none. "
        "The English is what the lexicon lists for a word. "
        "A word with no English is listed at the end, and no meaning has been filled in for it."
    )


def _unique(path: Path, index: int, what: str, raw: list) -> list[str]:
    """The texts of a list as written, each once. Capitals do not make two."""
    kept: list[str] = []
    seen: set[str] = set()
    for item in raw:
        if not isinstance(item, str):
            raise EnochaeonError(f"{path.name} entry {index} has a {what} that is not text.")
        text = " ".join(item.split())
        if text and text.casefold() not in seen:
            seen.add(text.casefold())
            kept.append(text)
    return kept


def _md(text: str) -> str:
    """Text for one cell of a Markdown table."""
    return "".join("\\" + character if character in _MARKDOWN_MARKS else character for character in text)


def _h(text: str) -> str:
    return html.escape(text)


def _letters(word: str) -> str:
    return f'<td class="en">{_h(fold(word))}</td>'


